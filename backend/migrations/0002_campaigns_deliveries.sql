-- Campaigns (docs/PLAN.md section 1 state machine) and the delivery queue.

CREATE TABLE campaigns (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brief        TEXT        NOT NULL,
    status       TEXT        NOT NULL DEFAULT 'draft'
                 CHECK (status IN ('draft', 'audience_ready', 'content_ready', 'approved',
                                   'sending', 'completed', 'completed_with_failures')),
    channels     TEXT[]      NOT NULL DEFAULT ARRAY['sms', 'email'],
    -- segment rule and content as validated JSON; they are frozen once the campaign is approved
    segment_rule JSONB,
    content      JSONB,
    approved_at  TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT campaigns_channels_valid
        CHECK (cardinality(channels) > 0 AND channels <@ ARRAY['sms', 'email']),
    -- a state implies the data it was reached with
    CONSTRAINT campaigns_audience_has_rule
        CHECK (status = 'draft' OR segment_rule IS NOT NULL),
    CONSTRAINT campaigns_content_has_content
        CHECK (status IN ('draft', 'audience_ready') OR content IS NOT NULL),
    CONSTRAINT campaigns_approved_has_time
        CHECK (status IN ('draft', 'audience_ready', 'content_ready') OR approved_at IS NOT NULL),
    CONSTRAINT campaigns_finished_has_time
        CHECK (status NOT IN ('completed', 'completed_with_failures') OR completed_at IS NOT NULL)
);

-- One row per (campaign, user, channel): the recipient list frozen at approval and the queue.
--
-- status:  queued   waiting for next_attempt_at (attempts > 0 means it is being retried)
--          sending  claimed by a worker until lease_until
--          sent     the provider accepted it (2xx)
--          failed   permanent error or attempts exhausted
--          skipped  the user withdrew consent for the channel before it was sent
CREATE TABLE deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id     BIGINT      NOT NULL REFERENCES campaigns (id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel         TEXT        NOT NULL CHECK (channel IN ('sms', 'email')),
    status          TEXT        NOT NULL DEFAULT 'queued'
                    CHECK (status IN ('queued', 'sending', 'sent', 'failed', 'skipped')),
    attempts        INTEGER     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    lease_until     TIMESTAMPTZ,
    last_error      TEXT        NOT NULL DEFAULT '',
    sent_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT deliveries_once_per_campaign UNIQUE (campaign_id, user_id, channel),
    -- the lease exists exactly while a delivery is being sent
    CONSTRAINT deliveries_lease_while_sending CHECK ((status = 'sending') = (lease_until IS NOT NULL)),
    CONSTRAINT deliveries_sent_has_time CHECK ((status = 'sent') = (sent_at IS NOT NULL))
);

-- Claim query: the next due queued delivery of one channel.
CREATE INDEX deliveries_claim_idx ON deliveries (channel, next_attempt_at, id) WHERE status = 'queued';
-- Lease recovery: expired leases.
CREATE INDEX deliveries_lease_idx ON deliveries (lease_until) WHERE status = 'sending';
-- Progress counts per campaign and status (dashboard, completion check).
CREATE INDEX deliveries_campaign_status_idx ON deliveries (campaign_id, status);
