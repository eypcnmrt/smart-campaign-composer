-- Users and their behavioural events.
--
-- Contract with internal/segment: the compiled segment predicate aliases users as u and
-- reads u.city, u.language, u.total_orders, u.total_spent_kurus, u.id, and from events
-- user_id, event_type and occurred_at. Every user column is NOT NULL, because "neq" and
-- "not_in" compile to <> and <> ALL, which are NULL (not true) for a NULL column and would
-- silently drop users from a segment.

CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        TEXT        NOT NULL,
    email             TEXT        NOT NULL UNIQUE,
    phone             TEXT        NOT NULL UNIQUE,
    city              TEXT        NOT NULL,
    language          TEXT        NOT NULL,
    total_orders      INTEGER     NOT NULL DEFAULT 0 CHECK (total_orders >= 0),
    total_spent_kurus BIGINT      NOT NULL DEFAULT 0 CHECK (total_spent_kurus >= 0),
    sms_consent       BOOLEAN     NOT NULL,
    email_consent     BOOLEAN     NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    event_type  TEXT        NOT NULL CHECK (event_type IN ('cart_add', 'purchase')),
    occurred_at TIMESTAMPTZ NOT NULL
);

-- Serves the compiled EXISTS / NOT EXISTS probe:
--   e.user_id = u.id AND e.event_type = $n AND e.occurred_at >= $m
CREATE INDEX events_user_type_time_idx ON events (user_id, event_type, occurred_at);
